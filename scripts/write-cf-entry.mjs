/**
 * Workers treat every named export of the entry module as a handler.
 * Nitro's bundle exports app symbols too, so the entry must re-export
 * only the default fetch handler.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const entry = join(dirname(fileURLToPath(import.meta.url)), "..", ".output", "server", "staging-entry.mjs");
writeFileSync(
  entry,
  `// Generated by scripts/write-cf-entry.mjs. Do not edit.\nexport { default } from "./index.mjs";\n`,
);
console.log("[build:cf] wrote", entry);
