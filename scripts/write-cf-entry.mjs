/**
 * Workers treat every named export of the entry module as a handler.
 * Nitro's bundle exports app symbols too, so the entry must re-export
 * only the default fetch handler.
 */
import { writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { buildOutput } from "./build-output.mjs";

const { serverEntry, workerEntry } = buildOutput("cloudflare-module");
const entry = join(process.cwd(), workerEntry);
writeFileSync(
  entry,
  `// Generated by scripts/write-cf-entry.mjs. Do not edit.\nexport { default } from "./${basename(serverEntry)}";\n`,
);
console.log("[build:cf] wrote", entry);
